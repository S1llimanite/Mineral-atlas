/** 光程差 (nm) → 干涉色 RGB。R ≥ 6000 视为高级白（饱和度衰减） */
export function michelLevyRGB(R: number): [number, number, number] {
  if (R <= 0) return [0, 0, 0];
  const A = ML_ANCHORS;
  if (R >= A[A.length - 1][0]) {
    const last = A[A.length - 1];
    return [last[1], last[2], last[3]];
  }
  // 线性插值
  for (let i = 1; i < A.length; i++) {
    if (R <= A[i][0]) {
      const [r0, g0, b0] = [A[i - 1][1], A[i - 1][2], A[i - 1][3]];
      const [r1, g1, b1] = [A[i][1], A[i][2], A[i][3]];
      const t = (R - A[i - 1][0]) / (A[i][0] - A[i - 1][0]);
      return [r0 + (r1 - r0) * t, g0 + (g1 - g0) * t, b0 + (b1 - b0) * t];
    }
  }
  return [0, 0, 0];
}

/** hex → [r,g,b] */
export function hexToRgb(hex: string): [number, number, number] {
  const h = hex.replace('#', '');
  return [
    parseInt(h.slice(0, 2), 16),
    parseInt(h.slice(2, 4), 16),
    parseInt(h.slice(4, 6), 16),
  ];
}

/** 种子随机数（mulberry32）：同一 seed 序列确定，保证同一矿物晶粒分布稳定 */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** 字符串 → 稳定数字种子 */
export function hashSeed(str: string): number {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** 标准薄片厚度（μm）——光程差计算的物理前提 */
export const THIN_SECTION_THICKNESS_UM = 30;

/** 双折射率 δ → 光程差 R (nm)：R = δ × 30μm = δ × 30000 nm */
export function birefringenceToRetardation(delta: number): number {
  return delta * THIN_SECTION_THICKNESS_UM * 1000;
}